public class HashingExample {

    public static void main(String[] args) {

        String str1 = "Java";
        String str2 = "Python";
        String str3 = "C++";

        System.out.println("HashCode of Java: " + str1.hashCode());
        System.out.println("HashCode of Python: " + str2.hashCode());
        System.out.println("HashCode of C++: " + str3.hashCode());

    }
}